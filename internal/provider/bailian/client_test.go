func TestBrowserTokenUsesQuotaGatewayWithoutGeneratingCredentials(t *testing.T) {
	requests := 0
	client := NewClient(&http.Client{Transport: transportFunc(func(r *http.Request) (*http.Response, error) {
		requests++
		if r.URL.Host != "bailian-cs.console.aliyun.com" || r.Header.Get("Authorization") != "Bearer illustrative-token" {
			t.Fatal("browser authorization used an unexpected endpoint or credential")
		}
		body, _ := io.ReadAll(r.Body)
		form, _ := url.ParseQuery(string(body))
		var params struct {
			Data struct {
				Context struct {
					SwitchAgent int64 `json:"switchAgent"`
				} `json:"cornerstoneParam"`
			}
		}
		if json.Unmarshal([]byte(form.Get("params")), &params) != nil || params.Data.Context.SwitchAgent != 123 {
			t.Fatal("delegated console context was not retained")
		}
		return &http.Response{StatusCode: 200, Body: io.NopCloser(strings.NewReader(`{"per1WeekPercentage":0.25}`))}, nil
	})})
	snapshot, err := client.Usage(context.Background(), Credentials{AccessToken: "illustrative-token", ConsoleSwitchAgent: 123})
	if err != nil || requests != 1 || snapshot.Weekly.RemainingPercent != 75 {
		t.Fatalf("browser quota failed: %+v %v, requests=%d", snapshot, err, requests)
	}
}

func TestQuotaCredentialsRejectMixedOrIncompleteAuthorization(t *testing.T) {
	for _, credentials := range []Credentials{{}, {AccessKeyID: "id"}, {AccessKeySecret: "secret"}, {AccessToken: "token", AccessKeyID: "id"}, {AccessToken: "token", ConsoleSwitchAgent: -1}} {
		if credentials.Valid() {
			t.Fatal("invalid credential combination accepted")
		}
	}
}

func TestBrowserTokenHTTPUnauthorizedMeansExpiredAuthorization(t *testing.T) {
	client := NewClient(&http.Client{Transport: transportFunc(func(*http.Request) (*http.Response, error) {
		return &http.Response{StatusCode: http.StatusUnauthorized, Body: io.NopCloser(strings.NewReader(""))}, nil
	})})
	_, err := client.Usage(context.Background(), Credentials{AccessToken: "illustrative-token"})
	if !errors.Is(err, ErrAuthorizationExpired) {
		t.Fatalf("unexpected expiry error: %v", err)
	}
}

type transportFunc func(*http.Request) (*http.Response, error)

func (f transportFunc) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }

func TestSigningMatchesOfficialCLIFixture(t *testing.T) {
	// Generated by the official CLI signer using illustrative credentials.
	req, _ := http.NewRequest(http.MethodPost, "https://modelstudio.cn-beijing.aliyuncs.com/modelstudio/cli/generateAccessToken", nil)
	signRequest(req, Credentials{AccessKeyID: "illustrative-id", AccessKeySecret: "illustrative-secret"}, "2026-10-14T07:44:31Z", "bf993ac4-91e1-4183-a9d5-06a0462d1675")
	if !strings.HasSuffix(req.Header.Get("Authorization"), "Signature=21bba9cd0274ca8444738acbb3144b6cfbd509dac9b8b0e8c1fe72519b5a6bee") {
		t.Fatal("ACS3 signature differs from official CLI")
	}
}

func TestUsageRefreshesAuthorizationAndParsesConsoleEnvelope(t *testing.T) {
	requests := 0
	client := NewClient(&http.Client{Transport: transportFunc(func(r *http.Request) (*http.Response, error) {
		requests++
		body := `{"cliAccessToken":"illustrative-session"}`
		if r.URL.Host == "modelstudio.cn-beijing.aliyuncs.com" {
			if !strings.HasPrefix(r.Header.Get("Authorization"), "ACS3-HMAC-SHA256 Credential=illustrative-id,") || r.Header.Get("X-Acs-Action") != "GenerateCLIAccessToken" {
				t.Fatal("missing signed token request")
			}
		} else {
			if r.Header.Get("Authorization") != "Bearer illustrative-session" {
				t.Fatal("missing console token")
			}
			formBody, _ := io.ReadAll(r.Body)
			form, _ := url.ParseQuery(string(formBody))
			if form.Get("region") != "cn-beijing" || !strings.Contains(form.Get("params"), usageAPI) {
				t.Fatal("invalid quota request")
			}
			body = `{"data":{"success":true,"DataV2":{"data":{"data":{"per5HourPercentage":0.125,"per1WeekPercentage":0,"per5HourResetTime":1900000000000,"per1WeekResetTime":1900500000000}}}}}`
		}
		return &http.Response{StatusCode: 200, Body: io.NopCloser(strings.NewReader(body))}, nil
	})})
	for i := 0; i < 2; i++ {
		snapshot, err := client.Usage(context.Background(), Credentials{AccessKeyID: "illustrative-id", AccessKeySecret: "illustrative-secret"})
		if err != nil {
			t.Fatal(err)
		}
		if snapshot.FiveHour.RemainingPercent != 87.5 || snapshot.Weekly.RemainingPercent != 100 || snapshot.Weekly.ResetAt != 1900500000 {
			t.Fatalf("wrong quota: %+v", snapshot)
		}
	}
	if requests != 4 {
		t.Fatalf("authorization was not refreshed: %d requests", requests)
	}
}

func TestParseUsageDistinguishesMissingZeroAndRejectedQuota(t *testing.T) {
	for _, tc := range []struct {
		name, body string
		err        error
	}{
		{"no windows", `{}`, ErrInvalidResponse},
		{"negative", `{"per1WeekPercentage":-0.1}`, ErrInvalidResponse},
		{"permission", `{"data":{"success":false,"errorCode":"BailianGateway.Team.NotAuthorised"}}`, ErrPermissionDenied},
		{"login", `{"data":{"success":false,"errorCode":"BailianGateway.Login.NotLogined"}}`, ErrAuthorizationExpired},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := ParseUsage([]byte(tc.body))
			if !errors.Is(err, tc.err) {
				t.Fatalf("got %v", err)
			}
		})
	}
	snapshot, err := ParseUsage([]byte(`{"per1WeekPercentage":0}`))
	if err != nil || snapshot.FiveHour != nil || snapshot.Weekly.RemainingPercent != 100 {
		t.Fatalf("zero and missing window conflated: %+v %v", snapshot, err)
	}
}

func TestSupportsURLRequiresTheTokenPlanOrigin(t *testing.T) {
	for _, raw := range []string{"http://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1", "https://token-plan.cn-beijing.maas.aliyuncs.com.example.com/compatible-mode/v1", "https://dashscope.aliyuncs.com/compatible-mode/v1"} {
		if SupportsURL(raw) {
			t.Fatalf("unsupported origin accepted: %s", raw)
		}
	}
	if !SupportsURL("https://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1/") {
		t.Fatal("Token Plan origin not recognized")
	}
}
