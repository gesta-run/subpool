import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { BailianQuotaDialog } from './BailianQuotaDialog'
import type { ProviderAccount } from '../../types'

const account: ProviderAccount = { id: 'illustrative-account', display_name: 'Example Token Plan', provider: 'openai_compatible', status: 'active', quota_provider: 'bailian_token_plan' }
const ramAccount: ProviderAccount = { ...account, quota_authorized: true, quota_authorization_method: 'ram', quota_access_key_id_hint: '****1234' }
afterEach(() => {
  vi.unstubAllGlobals()
  vi.useRealTimers()
})

describe('BailianQuotaDialog configuration', () => {
  it('sends quota credentials only to the authenticated configuration endpoint', async () => {
    const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ quota_authorized: true }), { headers: { 'Content-Type': 'application/json' } }))
    vi.stubGlobal('fetch', fetch)
    const onSaved = vi.fn().mockResolvedValue(undefined)
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={account} onSaved={onSaved} onClose={onClose} />)
    fireEvent.click(screen.getByRole('button', { name: 'Authorization method' }))
    fireEvent.click(screen.getByRole('option', { name: 'RAM AccessKey (automatic renewal)' }))
    fireEvent.change(screen.getByLabelText(/AccessKey ID/), { target: { value: 'illustrative-id' } })
    fireEvent.change(screen.getByLabelText(/AccessKey secret/), { target: { value: 'illustrative-secret' } })
    fireEvent.click(screen.getByRole('button', { name: 'Connect quota' }))
    await waitFor(() => expect(onClose).toHaveBeenCalled())
    expect(fetch.mock.calls[0][0]).toBe('/api/v1/provider-accounts/illustrative-account/bailian-quota')
    expect(fetch.mock.calls[0][1]).toMatchObject({ method: 'PUT', credentials: 'same-origin', body: JSON.stringify({ access_key_id: 'illustrative-id', access_key_secret: 'illustrative-secret' }) })
    expect(onSaved).toHaveBeenCalledOnce()
  })

  it('imports a temporary console token without requesting an AccessKey', async () => {
    const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ quota_authorized: true }), { headers: { 'Content-Type': 'application/json' } }))
    vi.stubGlobal('fetch', fetch)
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={account} onSaved={vi.fn()} onClose={onClose} />)
    expect(screen.queryByLabelText('AccessKey ID')).not.toBeInTheDocument()
    expect(screen.getByText(/sign in again when it expires/)).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText(/Console access token/), { target: { value: ' illustrative-token ' } })
    fireEvent.click(screen.getByRole('button', { name: 'Connect quota' }))
    await waitFor(() => expect(onClose).toHaveBeenCalled())
    expect(fetch).toHaveBeenCalledOnce()
    expect(fetch.mock.calls[0][1]).toMatchObject({ method: 'PUT', body: JSON.stringify({ access_token: 'illustrative-token' }) })
  })

  it('keeps the dialog open when upstream permission is denied', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(JSON.stringify({ message: 'Grant Token Plan access' }), { status: 502, headers: { 'Content-Type': 'application/json' } })))
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={account} onSaved={vi.fn()} onClose={onClose} />)
    fireEvent.click(screen.getByRole('button', { name: 'Authorization method' }))
    fireEvent.click(screen.getByRole('option', { name: 'RAM AccessKey (automatic renewal)' }))
    fireEvent.change(screen.getByLabelText(/AccessKey ID/), { target: { value: 'illustrative-id' } })
    fireEvent.change(screen.getByLabelText(/AccessKey secret/), { target: { value: 'illustrative-secret' } })
    fireEvent.click(screen.getByRole('button', { name: 'Connect quota' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Grant Token Plan access')
    expect(onClose).not.toHaveBeenCalled()
  })

  it('uses the shared form layout and validates before sending credentials', () => {
    const fetch = vi.fn()
    vi.stubGlobal('fetch', fetch)
    render(<BailianQuotaDialog account={account} onSaved={vi.fn()} onClose={vi.fn()} />)
    const submit = screen.getByRole('button', { name: 'Connect quota' })
    expect(submit.closest('form')).toHaveClass('form-stack')
    expect(screen.getByText(/official Bailian CLI browser flow/).closest('.field')).not.toBeNull()
    expect(screen.queryByText('Enter a console access token.')).not.toBeInTheDocument()
    expect(submit).toBeEnabled()
    fireEvent.click(submit)
    expect(screen.getByLabelText(/Console access token/)).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByLabelText(/Console access token/)).toHaveFocus()
    expect(fetch).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Authorization method' }))
    fireEvent.click(screen.getByRole('option', { name: 'RAM AccessKey (automatic renewal)' }))
    expect(screen.queryByText('Enter a console access token.')).not.toBeInTheDocument()
    fireEvent.blur(screen.getByLabelText(/AccessKey ID/))
    expect(screen.getByLabelText(/AccessKey ID/)).toHaveAttribute('aria-describedby', 'bailian-key-id-error')
  })

  it('shows the correct disconnect state without requiring replacement credentials', async () => {
    let finish: (response: Response) => void = () => {}
    const fetch = vi.fn(() => new Promise<Response>((resolve) => { finish = resolve }))
    vi.stubGlobal('fetch', fetch)
    const onClose = vi.fn()
    const onSaved = vi.fn().mockResolvedValue(undefined)
    render(<BailianQuotaDialog account={ramAccount} onSaved={onSaved} onClose={onClose} />)
    expect(screen.getByRole('dialog', { name: 'Manage quota authorization' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Save changes' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Disconnect quota' }))
    expect(screen.getByRole('button', { name: 'Disconnecting…' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Replace credentials' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Close' })).toBeDisabled()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(onClose).not.toHaveBeenCalled()
    expect(fetch.mock.calls[0]).toEqual(['/api/v1/provider-accounts/illustrative-account/bailian-quota', expect.objectContaining({ method: 'DELETE', body: undefined })])
    finish(new Response(null, { status: 204 }))
    await waitFor(() => expect(onClose).toHaveBeenCalledOnce())
    expect(onSaved).toHaveBeenCalledOnce()
  })
})

describe('BailianQuotaDialog request lifecycle', () => {
  it.each(['save', 'disconnect'])('restores dismissal after a stalled %s request times out', async (action) => {
    vi.useFakeTimers()
    let signal: AbortSignal | undefined
    vi.stubGlobal('fetch', vi.fn((_path: string, init: RequestInit) => new Promise<Response>((_resolve, reject) => {
      signal = init.signal as AbortSignal
      signal.addEventListener('abort', () => reject(new DOMException('The operation was aborted.', 'AbortError')), { once: true })
    })))
    const onClose = vi.fn()
    const onSaved = vi.fn()
    render(<BailianQuotaDialog account={ramAccount} onSaved={onSaved} onClose={onClose} />)
    if (action === 'save') {
      fireEvent.click(screen.getByRole('button', { name: 'Replace credentials' }))
      fireEvent.change(screen.getByLabelText(/AccessKey ID/), { target: { value: 'illustrative-new-id' } })
      fireEvent.change(screen.getByLabelText(/AccessKey secret/), { target: { value: 'illustrative-new-secret' } })
    }
    fireEvent.click(screen.getByRole('button', { name: action === 'save' ? 'Save changes' : 'Disconnect quota' }))
    expect(screen.getByRole('button', { name: action === 'save' ? 'Keep current credentials' : 'Close' })).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Close dialog' })).not.toBeInTheDocument()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(onClose).not.toHaveBeenCalled()
    await act(async () => { await vi.advanceTimersByTimeAsync(20_000) })
    expect(signal?.aborted).toBe(true)
    expect(screen.getByRole('alert')).toHaveTextContent('The request timed out.')
    expect(screen.getByRole('alert')).toHaveTextContent('The authorization may already have changed.')
    expect(screen.getByRole('button', { name: action === 'save' ? 'Keep current credentials' : 'Close' })).toBeEnabled()
    expect(screen.getByRole('button', { name: 'Close dialog' })).toBeEnabled()
    expect(onSaved).not.toHaveBeenCalled()
    expect(onClose).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(onClose).toHaveBeenCalledOnce()
  })

  it.each(['save', 'disconnect'])('closes after a successful %s without waiting for the account refresh', async (action) => {
    vi.useFakeTimers()
    const fetch = vi.fn((_path: string, _init: RequestInit) => Promise.resolve(new Response(null, { status: 204 })))
    vi.stubGlobal('fetch', fetch)
    const onSaved = vi.fn(() => new Promise<void>(() => {}))
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={action === 'save' ? account : ramAccount} onSaved={onSaved} onClose={onClose} />)
    if (action === 'save') fireEvent.change(screen.getByLabelText(/Console access token/), { target: { value: 'illustrative-token' } })
    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: action === 'save' ? 'Connect quota' : 'Disconnect quota' }))
    })
    expect(onClose).toHaveBeenCalledOnce()
    expect(onSaved).toHaveBeenCalledOnce()
    expect(onClose.mock.invocationCallOrder[0]).toBeLessThan(onSaved.mock.invocationCallOrder[0])
    await act(async () => { await vi.advanceTimersByTimeAsync(20_000) })
    expect(fetch.mock.calls[0][1].signal?.aborted).toBe(false)
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })
})

describe('BailianQuotaDialog saved authorization', () => {
  it('shows saved RAM authorization without blank inputs or a save action', () => {
    const fetch = vi.fn()
    vi.stubGlobal('fetch', fetch)
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={ramAccount} onSaved={vi.fn()} onClose={onClose} />)
    const details = screen.getByLabelText('Saved quota authorization')
    expect(within(details).getByText('RAM AccessKey (automatic renewal)')).toBeInTheDocument()
    expect(within(details).getByText('****1234')).toBeInTheDocument()
    expect(within(details).getByText('AccessKey secret').nextElementSibling).toHaveTextContent('Saved securely')
    expect(screen.queryByRole('button', { name: 'Authorization method' })).not.toBeInTheDocument()
    expect(screen.queryByLabelText(/AccessKey ID/)).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Save changes' })).not.toBeInTheDocument()
    fireEvent.submit(screen.getByRole('button', { name: 'Replace credentials' }).closest('form')!)
    fireEvent.click(screen.getByRole('button', { name: 'Close' }))
    expect(fetch).not.toHaveBeenCalled()
    expect(onClose).toHaveBeenCalledOnce()
  })

  it('requires explicit replacement and never submits the masked AccessKey', async () => {
    const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ quota_authorized: true }), { headers: { 'Content-Type': 'application/json' } }))
    vi.stubGlobal('fetch', fetch)
    const onClose = vi.fn()
    render(<BailianQuotaDialog account={ramAccount} onSaved={vi.fn()} onClose={onClose} />)
    fireEvent.click(screen.getByRole('button', { name: 'Replace credentials' }))
    expect(screen.getByRole('button', { name: 'Authorization method' })).toHaveTextContent('RAM AccessKey (automatic renewal)')
    expect(screen.getByRole('button', { name: 'Authorization method' })).toHaveFocus()
    expect(screen.getByLabelText(/AccessKey ID/)).toHaveValue('')
    expect(screen.getByLabelText(/AccessKey secret/)).toHaveValue('')
    expect(screen.getByText(/Current credentials remain unchanged/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(screen.getByLabelText(/AccessKey ID/)).toHaveFocus()
    expect(fetch).not.toHaveBeenCalled()
    fireEvent.change(screen.getByLabelText(/AccessKey ID/), { target: { value: 'illustrative-new-id' } })
    fireEvent.change(screen.getByLabelText(/AccessKey secret/), { target: { value: 'illustrative-new-secret' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
    await waitFor(() => expect(onClose).toHaveBeenCalledOnce())
    expect(fetch.mock.calls[0][1]).toMatchObject({ method: 'PUT', body: JSON.stringify({ access_key_id: 'illustrative-new-id', access_key_secret: 'illustrative-new-secret' }) })
  })

  it('discards replacement values and errors when keeping current credentials', async () => {
    const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ message: 'Grant Token Plan access' }), { status: 502, headers: { 'Content-Type': 'application/json' } }))
    vi.stubGlobal('fetch', fetch)
    const onClose = vi.fn()
    const onSaved = vi.fn()
    render(<BailianQuotaDialog account={ramAccount} onSaved={onSaved} onClose={onClose} />)
    fireEvent.click(screen.getByRole('button', { name: 'Replace credentials' }))
    fireEvent.change(screen.getByLabelText(/AccessKey ID/), { target: { value: 'illustrative-new-id' } })
    fireEvent.change(screen.getByLabelText(/AccessKey secret/), { target: { value: 'illustrative-new-secret' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Grant Token Plan access')
    expect(onClose).not.toHaveBeenCalled()
    expect(onSaved).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Authorization method' }))
    fireEvent.click(screen.getByRole('option', { name: 'Browser token (temporary)' }))
    fireEvent.change(screen.getByLabelText(/Console access token/), { target: { value: 'illustrative-new-token' } })
    fireEvent.click(screen.getByRole('button', { name: 'Keep current credentials' }))
    expect(screen.getByText('****1234')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Replace credentials' })).toHaveFocus()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(fetch).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button', { name: 'Replace credentials' }))
    expect(screen.getByRole('button', { name: 'Authorization method' })).toHaveTextContent('RAM AccessKey (automatic renewal)')
    expect(screen.getByLabelText(/AccessKey ID/)).toHaveValue('')
    expect(screen.getByLabelText(/AccessKey secret/)).toHaveValue('')
    fireEvent.click(screen.getByRole('button', { name: 'Authorization method' }))
    fireEvent.click(screen.getByRole('option', { name: 'Browser token (temporary)' }))
    expect(screen.getByLabelText(/Console access token/)).toHaveValue('')
  })

  it('shows saved browser authorization and starts replacement with the same method', () => {
    vi.stubGlobal('fetch', vi.fn())
    render(<BailianQuotaDialog account={{ ...account, quota_authorized: true, quota_authorization_method: 'browser' }} onSaved={vi.fn()} onClose={vi.fn()} />)
    const details = screen.getByLabelText('Saved quota authorization')
    expect(within(details).getByText('Browser token (temporary)')).toBeInTheDocument()
    expect(within(details).getByText('Console access token').nextElementSibling).toHaveTextContent('Saved securely')
    expect(screen.queryByLabelText(/Console access token/)).not.toBeInTheDocument()
    expect(screen.getByText(/Replace the saved token when it expires/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Replace credentials' }))
    expect(screen.getByRole('button', { name: 'Authorization method' })).toHaveTextContent('Browser token (temporary)')
    expect(screen.getByLabelText(/Console access token/)).toHaveValue('')
    expect(screen.queryByLabelText(/AccessKey ID/)).not.toBeInTheDocument()
  })
})
